/// The day the example data are written for.
final Day exampleToday = Day(2026, 9, 23);

/// A complete example of the export format `morphhealth-export`.
///
/// It is produced by reading the hand-written data below with the regular
/// import and writing them with the regular export. The result is therefore
/// exactly what the app exports, can be imported as it is and comes back
/// unchanged from the next export (apart from `exported_at`).
Map<String, dynamic> exampleDocument() {
  final now = LocalDateTime(exampleToday, 20, 0, 0, 120);
  final log = IssueLog();
  final data = AppData.fromDocument(_seed(), log, now: now);
  if (data == null) {
    throw StateError('The built-in example is invalid: ${log.errors}');
  }
  return data.toDocument(exportedAt: now, appVersion: morphHealthVersion);
}

