/// Bilingual string catalogue of MorphHealth.
///
/// German is the default language, English is fully supported. The catalogue
/// lives in the shared core package so that the Flutter app and the `mh`
/// maintenance CLI always use the same wording.
library;

import 'package:meta/meta.dart';

@immutable
class Strings {
  const Strings(this.languageCode);

  /// German catalogue (default).
  static const Strings de = Strings('de');

  /// English catalogue.
  static const Strings en = Strings('en');

  final String languageCode;

  bool get isGerman => languageCode == 'de';

  /// Returns the translation for [key] or the key itself when unknown.
  String t(String key, [Map<String, String> params = const <String, String>{}]) {
    final Map<String, String> table = isGerman ? _de : _en;
    String value = table[key] ?? _de[key] ?? key;
    params.forEach((String name, String replacement) {
      value = value.replaceAll('{$name}', replacement);
    });
    return value;
  }

  /// Format helper that keeps the call sites short.
  String call(String key, [Map<String, String> params = const <String, String>{}]) =>
      t(key, params);

  /// All keys of the catalogue, used by the consistency test.
  static Set<String> get allKeys => _de.keys.toSet();
}

