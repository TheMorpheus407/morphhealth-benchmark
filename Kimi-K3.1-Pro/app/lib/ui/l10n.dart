  String t(String key, [Map<String, Object?> values = const {}]) {
    final language = locale.languageCode == 'en' ? 'en' : 'de';
    var text = _strings[language]?[key] ?? _strings['de']![key] ?? key;
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return text;
  }

  String nutrient(Nutrient nutrient) => t('nutrient_${nutrient.id}');
  String meal(String meal) => t('meal_$meal');
  String flow(String flow) => t('flow_$flow');

  String number(num value, {int decimals = 2}) {
    final pattern = decimals == 0
        ? '0'
        : '0.${List.filled(decimals, '#').join()}';
    return NumberFormat(pattern, locale.languageCode).format(value);
  }

  String amount(num value, String unit, {int decimals = 2}) =>
      '${number(value, decimals: decimals)} $unit';

  String date(String value) =>
      DateFormat.yMMMd(locale.languageCode).format(DateTime.parse(value));
  String dateTime(DateTime value) =>
      DateFormat.yMMMd(locale.languageCode).add_Hm().format(value.toLocal());
  String time(DateTime value) =>
      DateFormat.Hm(locale.languageCode).format(value.toLocal());

